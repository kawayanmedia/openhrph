    public function getCompensationsFormatAttribute()
    {
        return collect($this->compensations)->sum('amount');
    }

    /**
     * The compensation lines that were broken out into their own payroll detail
     * column, keyed by the column label.
     *
     * @return array<string, float>
     */
    public function getCompensationBreakdownAttribute(): array
    {
        $breakdown = [];

        foreach (Compensation::taxClassColumns() as $column) {
            $amount = (float) $this->getAttribute($column);

            if ($amount !== 0.0) {
                $breakdown[Compensation::taxClassColumnLabel($column)] = $amount;
            }
        }

        return $breakdown;
    }

    /**
     * Compensation kept on the `incentive` total because its tax class has no
     * dedicated column, so the detail screen does not show it twice.
     */
    public function getOtherCompensationsAttribute(): float
    {
        return round((float) $this->incentive - array_sum($this->compensation_breakdown), 2);
    }

    /**
     * The itemised compensation lines in pesos, in the order payroll recorded
     * them.
     *
     * @return list<array{name: string, amount: float, taxable: bool}>
     */
    public function getCompensationLinesAttribute(): array
    {
        return collect($this->compensations ?? [])
            ->map(fn ($line): array => [
                'name' => (string) ($line['name'] ?? ''),
                'amount' => ((int) ($line['amount'] ?? 0)) / 100,
                'taxable' => (bool) ($line['taxable'] ?? true),
            ])
            ->values()
            ->all();
    }

    /**
     * Compensation held on the `incentive` total that the itemised lines do not
     * account for. Normally zero; a run written before itemisation can differ.
     */
    public function getUnitemisedIncentiveAttribute(): float
    {
        $itemised = array_sum(array_column($this->compensation_lines, 'amount'));

        return round((float) $this->incentive - $itemised, 2);
    }

